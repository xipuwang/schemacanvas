#!/usr/bin/env node
// Third-party notices for the published site: builds once with source maps into .tmp/notices-build, collects every
// node_modules package whose code ends up in a shipped JS/CSS file, and writes public/THIRD-PARTY-NOTICES.txt (Vite copies
// public/ verbatim into dist/, so the notices ship next to index.html). Re-run after changing dependencies:
//   node scripts/gen-notices.mjs
import { execSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const out = '.tmp/notices-build';
execSync(`npx vite build --outDir ${out} --emptyOutDir --sourcemap`, { stdio: 'ignore' });

const packages = new Set();
const dir = join(out, 'assets');
for (const f of readdirSync(dir).filter((x) => x.endsWith('.map'))) {
  for (const s of JSON.parse(readFileSync(join(dir, f), 'utf8')).sources ?? []) {
    const i = s.lastIndexOf('node_modules/');
    if (i < 0) continue;
    const parts = s.slice(i + 'node_modules/'.length).split('/');
    packages.add(parts[0].startsWith('@') ? `${parts[0]}/${parts[1]}` : parts[0]);
  }
}
// Fonts ship as CSS + woff2; CSS source maps do not always list them, so add the font packages the app imports.
const pkgJson = JSON.parse(readFileSync('package.json', 'utf8'));
for (const dep of Object.keys(pkgJson.dependencies)) if (dep.startsWith('@fontsource')) packages.add(dep);

// Packages whose licence asks for a pointer to the source code (EPL-2.0 section 3.2) or that need a short explanation.
const EXTRA = {
  elkjs: 'Used under EPL-2.0 (the package is dual licensed EPL-2.0 OR GPL-3.0-or-later). Source code: https://github.com/kieler/elkjs (Eclipse Layout Kernel: https://github.com/eclipse/elk).',
  dompurify: 'Used under Apache-2.0 (the package is dual licensed MPL-2.0 OR Apache-2.0).',
};

const licenseText = (root) => {
  const file = readdirSync(root).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f)) ?? readdirSync(root).find((f) => /^licen[cs]e/i.test(f));
  return file ? readFileSync(join(root, file), 'utf8').trim() : undefined;
};

const sections = [];
for (const name of [...packages].sort()) {
  const root = join('node_modules', name);
  if (!existsSync(join(root, 'package.json'))) continue;
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  const text = licenseText(root);
  if (!text) throw new Error(`no licence file found for ${name}; add it by hand before publishing`);
  sections.push(
    [`${name} ${pkg.version}`, `License: ${pkg.license}`, repo ? `Repository: ${repo.replace(/^git\+/, '')}` : '', EXTRA[name] ?? '', '', text]
      .filter((l, i) => l !== '' || i === 4)
      .join('\n'),
  );
}

const header = `SchemaCanvas includes the following third-party software. Each component is distributed under its own licence, reproduced below.
Generated by scripts/gen-notices.mjs from the production build; ${sections.length} components.`;
mkdirSync('public', { recursive: true });
writeFileSync('public/THIRD-PARTY-NOTICES.txt', `${header}\n\n${sections.join(`\n\n${'='.repeat(100)}\n\n`)}\n`);
console.log(`public/THIRD-PARTY-NOTICES.txt: ${sections.length} components`);
