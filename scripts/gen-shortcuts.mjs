#!/usr/bin/env node
// Generates docs/SHORTCUTS.md from the REAL command registry (src/editor/commands/registry.ts), so the table cannot drift.
//
//   node scripts/gen-shortcuts.mjs            write docs/SHORTCUTS.md
//   node scripts/gen-shortcuts.mjs --check    exit 1 when the committed file is out of date (CI / pre-release)
//
// It loads the same modules the app registers its commands from (editor commands, keyboard layer, editor tools, shell
// commands) through Vite's SSR loader (so the `@/` alias and the i18n catalogues resolve exactly as in the app), then
// formats every command that has a shortcut with the app's own formatShortcut() for both platforms.
import { createServer } from 'vite';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const target = join(root, 'docs', 'SHORTCUTS.md');
const check = process.argv.includes('--check');

const vite = await createServer({ root, appType: 'custom', server: { middlewareMode: true }, logLevel: 'error', optimizeDeps: { noDiscovery: true, include: [] } });
let md;
try {
  await vite.ssrLoadModule('/src/editor/tools/index.ts'); // registers tools + keyboard layer (+ editor commands via ./commands)
  const editor = await vite.ssrLoadModule('/src/editor/index.ts');
  const shell = await vite.ssrLoadModule('/src/ui/shell/commands.ts');
  const i18n = await vite.ssrLoadModule('/src/i18n/index.ts');
  shell.registerShellCommands();

  const GROUP_ORDER = ['file', 'edit', 'tools', 'view', 'arrange', 'diagram', 'help'];
  const GROUP_TITLE = { file: 'File', edit: 'Edit', tools: 'Tools and settings', view: 'View', arrange: 'Arrange', diagram: 'Diagram', help: 'Help' };
  const keysOf = (c) => (c.shortcut === undefined ? [] : Array.isArray(c.shortcut) ? c.shortcut : [c.shortcut]);
  const cell = (s) => '`' + s.replace(/\|/g, '\\|') + '`';
  const commands = editor.listCommands().filter((c) => keysOf(c).length > 0);

  const lines = [
    '# Keyboard shortcuts',
    '',
    '<!-- GENERATED by scripts/gen-shortcuts.mjs from the command registry. Do not edit by hand: run `npm run docs:shortcuts`. -->',
    '',
    'Every toolbar button, menu entry, context-menu item, keyboard shortcut and the command palette (`Ctrl/Cmd+K`) call the same',
    'command registry, so this list is exactly what the in-app dialog (`?` or `F1`) shows. `Mod` is `Cmd` on macOS and `Ctrl` elsewhere.',
    'A few commands share a key and apply in different situations (for example `Enter` edits the selected element, or enters a table\'s cell mode);',
    'the app runs the first one that is enabled for the current selection.',
    '',
  ];
  for (const group of GROUP_ORDER) {
    const items = commands.filter((c) => c.group === group).sort((a, b) => a.id.localeCompare(b.id));
    if (!items.length) continue;
    lines.push(`## ${GROUP_TITLE[group]}`, '', '| Command | Windows / Linux | macOS | Command id |', '|---|---|---|---|');
    for (const c of items) {
      const label = i18n.t(c.labelKey, undefined);
      const win = keysOf(c).map((s) => cell(editor.formatShortcut(s, false))).join(' or ');
      const mac = keysOf(c).map((s) => cell(editor.formatShortcut(s, true))).join(' or ');
      lines.push(`| ${label.replace(/\|/g, '\\|')} | ${win} | ${mac} | \`${c.id}\` |`);
    }
    lines.push('');
  }
  lines.push(`${commands.length} commands have shortcuts. Pointer gestures (wheel to zoom, Space+drag or middle button to pan, drag handles) are described in the user guide.`, '');
  md = lines.join('\n');
} finally {
  await vite.close();
}

if (check) {
  const cur = (() => { try { return readFileSync(target, 'utf8'); } catch { return ''; } })();
  if (cur !== md) {
    console.error('docs/SHORTCUTS.md is out of date: run `npm run docs:shortcuts`');
    process.exit(1);
  }
  console.log('docs/SHORTCUTS.md is up to date');
} else {
  writeFileSync(target, md);
  console.log(`wrote docs/SHORTCUTS.md`);
}
