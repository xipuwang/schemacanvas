/**
 * A tiny, lossless tokenizer for SQL DDL and DBML (display only). Joining the token texts of a line gives the line back.
 * No dependency: comments, strings, quoted identifiers, numbers, keywords and type names are distinguished.
 */
export type TokenKind = 'kw' | 'type' | 'str' | 'com' | 'id' | 'num' | 'plain';
export interface Token {
  text: string;
  kind: TokenKind;
}
export type Lang = 'sql' | 'dbml';

const SQL_KEYWORDS = new Set(
  (
    'create table index unique primary key foreign references constraint not null default check alter add on delete update cascade restrict set no action ' +
    'if exists schema autoincrement auto_increment generated by as identity always using engine drop collate with and or in is deferrable initially deferred ' +
    'comment charset character unsigned zerofill stored virtual to rename column temporary view'
  ).split(' '),
);
const DBML_KEYWORDS = new Set('table ref enum note project indexes pk primary key unique null not default increment as headercolor tablegroup'.split(' '));
const TYPES = new Set(
  (
    'int integer bigint smallint tinyint mediumint serial bigserial smallserial varchar char nchar nvarchar text tinytext mediumtext longtext date time timestamp timestamptz ' +
    'datetime year boolean bool numeric decimal real float double precision blob tinyblob longblob bytea uuid json jsonb enum varbinary binary bit money interval'
  ).split(' '),
);

const WORD = /^[A-Za-z_][A-Za-z0-9_$]*/;
const NUMBER = /^\d+(?:\.\d+)?/;

export function highlight(text: string, lang: Lang): Token[][] {
  const keywords = lang === 'dbml' ? DBML_KEYWORDS : SQL_KEYWORDS;
  const lineComment = lang === 'dbml' ? '//' : '--';
  let inBlock = false;
  return text.split(/\r\n|\r|\n/).map((line) => {
    const out: Token[] = [];
    const push = (s: string, kind: TokenKind): void => {
      if (!s) return;
      const last = out[out.length - 1];
      if (last && last.kind === kind && (kind === 'plain' || kind === 'com')) last.text += s;
      else out.push({ text: s, kind });
    };
    let i = 0;
    while (i < line.length) {
      if (inBlock) {
        const end = line.indexOf('*/', i);
        if (end < 0) {
          push(line.slice(i), 'com');
          i = line.length;
        } else {
          push(line.slice(i, end + 2), 'com');
          i = end + 2;
          inBlock = false;
        }
        continue;
      }
      const rest = line.slice(i);
      if (rest.startsWith(lineComment)) {
        push(rest, 'com');
        break;
      }
      if (rest.startsWith('/*')) {
        inBlock = true;
        push('/*', 'com');
        i += 2;
        continue;
      }
      const c = rest[0]!;
      if (c === "'" || c === '"' || c === '`') {
        let j = 1;
        while (j < rest.length) {
          if (rest[j] === c) {
            if (rest[j + 1] === c) j += 2; // doubled quote escape
            else break;
          } else j++;
        }
        const s = rest.slice(0, Math.min(rest.length, j + 1));
        push(s, c === "'" ? 'str' : 'id');
        i += s.length;
        continue;
      }
      const num = NUMBER.exec(rest);
      if (num) {
        push(num[0], 'num');
        i += num[0].length;
        continue;
      }
      const word = WORD.exec(rest);
      if (word) {
        const lower = word[0].toLowerCase();
        push(word[0], keywords.has(lower) ? 'kw' : TYPES.has(lower) ? 'type' : 'plain');
        i += word[0].length;
        continue;
      }
      push(c, 'plain');
      i += 1;
    }
    return out;
  });
}
