import { describe, expect, it } from 'vitest';
import { SqlParseError } from './types';
import { parseDdl, parseDdlSafe } from './ddlParser';
import { shapeOf } from './testing';

const rel = (text: string, name: string, dialect: Parameters<typeof parseDdl>[1] = 'auto') => {
  const { model, warnings } = parseDdl(text, dialect);
  const r = Object.values(model.relations).find((x) => x.name === name);
  if (!r) throw new Error(`no relation ${name}`);
  return { model, warnings, r, col: (n: string) => r.columns.find((c) => c.name === n)! };
};
const err = (text: string, dialect: Parameters<typeof parseDdl>[1] = 'auto'): SqlParseError => {
  try {
    parseDdl(text, dialect);
  } catch (e) {
    expect(e).toBeInstanceOf(SqlParseError);
    return e as SqlParseError;
  }
  throw new Error('expected a SqlParseError');
};

describe('CREATE TABLE basics', () => {
  it('parses columns, types, NOT NULL, DEFAULT, comments and several statements', () => {
    const { r, col, warnings, model } = rel(
      `-- header comment
      /* block
         comment */
      CREATE TABLE IF NOT EXISTS Student (
        SID integer PRIMARY KEY,           -- trailing
        FirstName varchar(40) NOT NULL,
        GPA numeric(3, 2) DEFAULT 0.0,
        Born date NULL,
        Status text NOT NULL DEFAULT 'it''s ok',
        Created timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
        Score double precision DEFAULT -1
      );
      CREATE TABLE Other (a INT);`,
      'Student',
    );
    expect(Object.keys(model.relations)).toHaveLength(2);
    expect(r.columns.map((c) => c.name)).toEqual(['SID', 'FirstName', 'GPA', 'Born', 'Status', 'Created', 'Score']);
    expect(r.primaryKey).toEqual([col('SID').id]);
    expect(col('SID').nullable).toBe(false);
    expect(col('FirstName')).toMatchObject({ dataType: 'VARCHAR(40)', nullable: false });
    expect(col('GPA').dataType).toBe('NUMERIC(3,2)');
    expect(col('GPA').defaultValue).toBe('0.0');
    expect(col('Born').nullable).toBe(true);
    expect(col('Status').defaultValue).toBe("'it''s ok'");
    expect(col('Created')).toMatchObject({ dataType: 'TIMESTAMP WITH TIME ZONE', defaultValue: 'CURRENT_TIMESTAMP', nullable: false });
    expect(col('Score')).toMatchObject({ dataType: 'DOUBLE PRECISION', defaultValue: '-1' });
    expect(warnings).toEqual([]);
  });

  it('handles quoted identifiers in all three styles and schema-qualified names', () => {
    const { model } = rel(
      `CREATE TABLE "my schema"."Odd ""Name""" ("a b" int, \`c\`\`d\` int, [e f] int);`,
      'Odd "Name"',
    );
    const r = Object.values(model.relations)[0]!;
    expect(r.schemaName).toBe('my schema');
    expect(r.name).toBe('Odd "Name"');
    expect(r.columns.map((c) => c.name)).toEqual(['a b', 'c`d', 'e f']);
  });

  it('parses multi-word and parameterised types, arrays and custom types', () => {
    const { col } = rel(
      `CREATE TABLE t (a character varying(10), b int unsigned, c numeric(10,2), d integer[], e "MyEnum", f enum('x','y'), g timestamp(3) without time zone);`,
      't',
    );
    expect(col('a').dataType).toBe('CHARACTER VARYING(10)');
    expect(col('b').dataType).toBe('INT UNSIGNED');
    expect(col('d').dataType).toBe('INTEGER[]');
    expect(col('e').dataType).toBe('"MyEnum"');
    expect(col('f').dataType).toBe("ENUM('x','y')");
    expect(col('g').dataType).toBe('TIMESTAMP(3) WITHOUT TIME ZONE');
  });

  it('typeless columns are allowed (SQLite)', () => {
    const { col } = rel('CREATE TABLE t (a, b PRIMARY KEY, c NOT NULL);', 't');
    expect(col('a').dataType).toBeUndefined();
    expect(col('c').nullable).toBe(false);
  });
});

describe('autoincrement normalisation', () => {
  it('SERIAL/BIGSERIAL/IDENTITY/AUTO_INCREMENT/AUTOINCREMENT become base type + autoIncrement', () => {
    const { col } = rel(
      `CREATE TABLE t (
        a serial, b bigserial, c smallserial,
        d integer GENERATED ALWAYS AS IDENTITY (START WITH 1),
        e bigint GENERATED BY DEFAULT AS IDENTITY,
        f int AUTO_INCREMENT,
        g integer PRIMARY KEY AUTOINCREMENT
      );`,
      't',
    );
    expect(col('a')).toMatchObject({ dataType: 'INTEGER', autoIncrement: true, nullable: false });
    expect(col('b')).toMatchObject({ dataType: 'BIGINT', autoIncrement: true });
    expect(col('c')).toMatchObject({ dataType: 'SMALLINT', autoIncrement: true });
    expect(col('d')).toMatchObject({ dataType: 'INTEGER', autoIncrement: true });
    expect(col('e')).toMatchObject({ dataType: 'BIGINT', autoIncrement: true });
    expect(col('f')).toMatchObject({ dataType: 'INT', autoIncrement: true });
    expect(col('g')).toMatchObject({ dataType: 'INTEGER', autoIncrement: true });
  });
});

describe('keys and constraints', () => {
  it('inline PK/UNIQUE/CHECK and named constraints', () => {
    const { r, col } = rel(
      `CREATE TABLE t (
        id int CONSTRAINT pk_t PRIMARY KEY,
        email text UNIQUE,
        code text CONSTRAINT uq_code UNIQUE,
        age int CHECK (age >= 0 AND age < 150),
        score int CONSTRAINT ck_score CHECK (score > 0)
      );`,
      't',
    );
    expect(r.primaryKey).toEqual([col('id').id]);
    expect(r.primaryKeyName).toBe('pk_t');
    expect(r.uniques.map((u) => [u.name, u.columnIds])).toEqual([[undefined, [col('email').id]], ['uq_code', [col('code').id]]]);
    expect(r.checks!.map((c) => [c.name, c.expression, c.columnIds])).toEqual([
      [undefined, 'age >= 0 AND age < 150', [col('age').id]],
      ['ck_score', 'score > 0', [col('score').id]],
    ]);
  });

  it('table-level composite PK, UNIQUE, CHECK, listed before columns they use', () => {
    const { r, col } = rel(
      `CREATE TABLE Drug (
        CompanyName text, TradeName text, Formula text,
        CONSTRAINT drug_pk PRIMARY KEY (CompanyName, TradeName),
        UNIQUE (Formula),
        CONSTRAINT u2 UNIQUE (Formula, TradeName),
        CHECK (length(Formula) > 0)
      );`,
      'Drug',
    );
    expect(r.primaryKey).toEqual([col('CompanyName').id, col('TradeName').id]);
    expect(r.primaryKeyName).toBe('drug_pk');
    expect(col('CompanyName').nullable).toBe(false);
    expect(r.uniques).toHaveLength(2);
    expect(r.uniques[1]).toMatchObject({ name: 'u2', columnIds: [col('Formula').id, col('TradeName').id] });
    expect(r.checks![0]!.columnIds).toEqual([col('Formula').id]);
  });

  it('inline and table-level foreign keys with actions, composite FKs and forward references', () => {
    const { model } = parseDdl(`
      CREATE TABLE Prescription (
        CompanyName text, DrugTradeName text, DoctorSSN char(9) REFERENCES Doctor,
        FOREIGN KEY (CompanyName, DrugTradeName) REFERENCES Drug (CompanyName, TradeName) ON DELETE CASCADE ON UPDATE SET NULL,
        CONSTRAINT fk_x FOREIGN KEY (DoctorSSN) REFERENCES Doctor (SSN) ON DELETE NO ACTION
      );
      CREATE TABLE Drug (CompanyName text, TradeName text, PRIMARY KEY (CompanyName, TradeName));
      CREATE TABLE Doctor (SSN char(9) PRIMARY KEY);
    `);
    const s = shapeOf(model).fks;
    expect(s).toEqual([
      'Prescription(CompanyName->CompanyName,DrugTradeName->TradeName)>Drug||CASCADE|SET NULL',
      'Prescription(DoctorSSN->SSN)>Doctor|fk_x|NO ACTION|',
      'Prescription(DoctorSSN->SSN)>Doctor|||',
    ].sort());
    // a composite FK is ONE ForeignKey with two ordered pairs
    expect(Object.values(model.foreignKeys).filter((f) => f.columns.length === 2)).toHaveLength(1);
  });

  it('inline REFERENCES without column list uses the target primary key', () => {
    const { model } = parseDdl('CREATE TABLE a (x int REFERENCES b); CREATE TABLE b (k int PRIMARY KEY);');
    expect(shapeOf(model).fks).toEqual(['a(x->k)>b|||']);
  });

  it('ALTER TABLE ADD PRIMARY KEY / UNIQUE / FOREIGN KEY / CHECK (pg_dump style)', () => {
    const { model, warnings } = parseDdl(`
      SET statement_timeout = 0;
      CREATE TABLE public.users (id integer NOT NULL, email text);
      CREATE TABLE public.posts (id integer NOT NULL, user_id integer);
      ALTER TABLE public.users OWNER TO postgres;
      ALTER TABLE ONLY public.users ADD CONSTRAINT users_pkey PRIMARY KEY (id);
      ALTER TABLE ONLY public.users ADD CONSTRAINT users_email_key UNIQUE (email);
      ALTER TABLE ONLY public.posts ADD CONSTRAINT posts_pkey PRIMARY KEY (id);
      ALTER TABLE ONLY public.posts ALTER COLUMN id SET DEFAULT nextval('public.posts_id_seq'::regclass);
      ALTER TABLE ONLY public.posts ADD CONSTRAINT posts_user_fk FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE;
      ALTER TABLE public.posts ADD CHECK (id > 0);
    `);
    expect(shapeOf(model).fks).toEqual(['posts(user_id->id)>users|posts_user_fk|CASCADE|']);
    const posts = Object.values(model.relations).find((r) => r.name === 'posts')!;
    expect(posts.primaryKeyName).toBe('posts_pkey');
    expect(posts.columns[0]!.defaultValue).toBe("nextval('public.posts_id_seq'::regclass)");
    expect(posts.checks).toHaveLength(1);
    expect(warnings.map((w) => w.params!.construct)).toEqual(['SET statement', 'OWNER TO']);
  });

  it('ALTER COLUMN ADD GENERATED / SET NOT NULL / DROP NOT NULL', () => {
    const { r, col } = rel(
      `CREATE TABLE t (id int, a int NOT NULL, b int);
       ALTER TABLE t ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY, ALTER COLUMN a DROP NOT NULL, ALTER COLUMN b SET NOT NULL;`,
      't',
    );
    expect(r.columns.length).toBe(3);
    expect(col('id')).toMatchObject({ autoIncrement: true, nullable: false });
    expect(col('a').nullable).toBe(true);
    expect(col('b').nullable).toBe(false);
  });

  it('MySQL inline KEY / UNIQUE KEY / USING', () => {
    const { r, col } = rel(
      `CREATE TABLE \`t\` (
        \`id\` int NOT NULL AUTO_INCREMENT, \`a\` varchar(10), \`b\` varchar(10),
        PRIMARY KEY (\`id\`) USING BTREE,
        UNIQUE KEY \`uq_a\` (\`a\`),
        KEY \`idx_b\` (\`b\` DESC) USING HASH
      ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='the t';`,
      't',
    );
    expect(r.uniques).toMatchObject([{ name: 'uq_a', columnIds: [col('a').id] }]);
    expect(r.indexes).toMatchObject([{ name: 'idx_b', unique: false, method: 'hash', descendingColumnIds: [col('b').id] }]);
    expect(r.description).toBe('the t');
  });
});

describe('CREATE INDEX', () => {
  it('unique, partial, method, DESC, IF NOT EXISTS, schema-qualified', () => {
    const { r, col } = rel(
      `CREATE TABLE s.t (a int, b int);
       CREATE UNIQUE INDEX IF NOT EXISTS ix1 ON s.t USING btree (a, b DESC) WHERE a > 0;
       CREATE INDEX ix2 ON t (b);`,
      't',
    );
    expect(r.indexes[0]).toMatchObject({ name: 'ix1', unique: true, method: 'btree', where: 'a > 0', columnIds: [col('a').id, col('b').id], descendingColumnIds: [col('b').id] });
    expect(r.indexes[1]).toMatchObject({ name: 'ix2', unique: false, columnIds: [col('b').id] });
  });
});

describe('dialect detection', () => {
  const d = (sql: string) => parseDdl(sql, 'auto').model.dialect;
  it('detects from signals', () => {
    expect(d('CREATE TABLE `t` (a int);')).toBe('mysql');
    expect(d('CREATE TABLE t (a int AUTO_INCREMENT);')).toBe('mysql');
    expect(d('CREATE TABLE t (a integer PRIMARY KEY AUTOINCREMENT);')).toBe('sqlite');
    expect(d('CREATE TABLE t (a serial);')).toBe('postgresql');
    expect(d('CREATE TABLE t (a int);')).toBe('generic');
  });
  it('an explicit dialect wins and restricts quoting', () => {
    expect(parseDdl('CREATE TABLE t (a int);', 'sqlite').model.dialect).toBe('sqlite');
    expect(err('CREATE TABLE `t` (a int);', 'postgresql').construct).toBe('`');
  });
});

describe('explicit warnings for skipped constructs', () => {
  it('views, triggers (with inner semicolons), INSERT, DROP and MySQL options are skipped WITH warnings naming them', () => {
    const { warnings, model } = parseDdl(`
      CREATE TABLE a (id int PRIMARY KEY, n text COLLATE nocase);
      CREATE VIEW v AS SELECT * FROM a;
      CREATE TRIGGER trg AFTER INSERT ON a BEGIN
        UPDATE a SET n = 'x' WHERE id = new.id;
        INSERT INTO a VALUES (1, CASE WHEN 1 THEN 'a' ELSE 'b' END);
      END;
      INSERT INTO a VALUES (1, 'x');
      DROP TABLE IF EXISTS zzz;
      CREATE TABLE b (id int) ENGINE=InnoDB AUTO_INCREMENT=5;
      /*!40101 SET NAMES utf8 */;
    `);
    expect(Object.keys(model.relations)).toHaveLength(2);
    const by = (c: string) => warnings.filter((w) => w.params!.construct === c);
    expect(by('CREATE VIEW')).toHaveLength(1);
    expect(by('CREATE TRIGGER')).toHaveLength(1);
    expect(by('INSERT statement')).toHaveLength(1);
    expect(by('DROP statement')).toHaveLength(1);
    expect(by('COLLATE')).toHaveLength(1);
    expect(by('table options')).toHaveLength(1);
    expect(by('/*! */')).toHaveLength(1);
    // positions are reported
    expect(by('CREATE VIEW')[0]!.params).toMatchObject({ line: 3 });
    expect(by('CREATE VIEW')[0]!.explanation).toMatch(/line 3/);
    for (const w of warnings) {
      expect(w.severity).toBe('warning');
      expect(w.code.startsWith('sql.import.')).toBe(true);
      expect(w.modelId).toBe(model.id);
    }
    expect(new Set(warnings.map((w) => w.id)).size).toBe(warnings.length);
  });
  it('FK to a non-key is imported with a warning', () => {
    const { warnings } = parseDdl('CREATE TABLE p (id int PRIMARY KEY, x int); CREATE TABLE c (px int REFERENCES p (x));');
    expect(warnings.map((w) => w.code)).toEqual(['sql.import.fk-target-not-key']);
  });
});

describe('errors carry line/column and name the construct', () => {
  it('unknown referenced table / column / arity mismatch', () => {
    const e1 = err('CREATE TABLE a (x int);\nCREATE TABLE b (y int REFERENCES nope (id));');
    expect(e1.message).toMatch(/nope/);
    expect([e1.line, e1.column]).toEqual([2, 34]);
    expect(err('CREATE TABLE a (x int); CREATE TABLE b (y int REFERENCES a (zzz));').message).toMatch(/a\.zzz/);
    expect(err('CREATE TABLE a (x int, z int, PRIMARY KEY (x, z)); CREATE TABLE b (y int, FOREIGN KEY (y) REFERENCES a);').message).toMatch(/1 column\(s\) but references 2/);
    expect(err('CREATE TABLE a (x int); CREATE TABLE b (y int REFERENCES a);').message).toMatch(/no primary key/);
  });
  it('syntax errors', () => {
    expect(err('CREATE TABLE t (a int,').message).toMatch(/Expected|end of input/);
    expect(err("CREATE TABLE t (a text DEFAULT 'oops);").message).toMatch(/Unterminated string/);
    expect(err('CREATE TABLE t (a int) /* never closed').message).toMatch(/Unterminated \/\* comment/);
    expect(err('CREATE TABLE t (a int PRIMARY KEY, b int PRIMARY KEY);').message).toMatch(/several primary keys/);
    expect(err('CREATE TABLE t (a int, a int);').message).toMatch(/Duplicate column a/);
    expect(err('CREATE TABLE t (a int); CREATE TABLE t (b int);').message).toMatch(/defined twice/);
    expect(err('CREATE TABLE t (a int, PRIMARY KEY (b));').message).toMatch(/Column b .* does not exist/);
    expect(err('CREATE TABLE t (a int) garbage garbage ( ; CREATE TABLE x (a int);').message).toMatch(/Unbalanced|\)/);
  });
  it('constructs that would change the schema are errors, not silent skips', () => {
    expect(err('CREATE TABLE t (a int, b int GENERATED ALWAYS AS (a + 1) STORED);').construct).toBe('GENERATED ALWAYS AS (expr)');
    expect(err('CREATE TABLE t (a int, b int AS (a + 1));').construct).toBe('AS (expr)');
    expect(err('CREATE TABLE t AS SELECT 1;').construct).toBe('CREATE TABLE AS');
    expect(err('CREATE TABLE t (a int WEIRDATTR);').construct).toBe('WEIRDATTR');
    expect(err('CREATE TABLE t (a int); ALTER TABLE t ADD COLUMN b int;').construct).toBe('ADD COLUMN');
    expect(err('CREATE TABLE t (a int); ALTER TABLE t DROP COLUMN a;').construct).toBe('DROP');
    expect(err('CREATE TABLE t (a int); CREATE INDEX i ON t (lower(a));').construct).toBe('expression key part');
    expect(err('CREATE TABLE t (a int) INHERITS (p);').construct).toBe('INHERITS');
    expect(err('CREATE TABLE t (a varchar(10), PRIMARY KEY (a(5)));').construct).toBe('key prefix length');
    expect(err('DELIMITER //\nCREATE TABLE t (a int)//').construct).toBe('DELIMITER');
    expect(err('FROBNICATE t;').construct).toBe('FROBNICATE');
    expect(err('ALTER TABLE missing ADD PRIMARY KEY (a);').message).toMatch(/missing is not defined/);
  });
  it('parseDdlSafe returns the typed error', () => {
    const r = parseDdlSafe('CREATE TABLE ;');
    expect(r.ok).toBe(false);
    if (!r.ok) expect(r.error).toBeInstanceOf(SqlParseError);
    expect(parseDdlSafe('CREATE TABLE t (a int);').ok).toBe(true);
  });
});

describe('ids', () => {
  it('imported ids use newId prefixes and are unique', () => {
    const { model } = parseDdl('CREATE TABLE a (x int PRIMARY KEY); CREATE TABLE b (y int REFERENCES a);');
    const ids = [
      model.id,
      ...Object.values(model.relations).flatMap((r) => [r.id, ...r.columns.map((c) => c.id)]),
      ...Object.keys(model.foreignKeys),
    ];
    expect(new Set(ids).size).toBe(ids.length);
    expect(Object.values(model.relations)[0]!.id).toMatch(/^rln_/);
    expect(Object.values(model.relations)[0]!.columns[0]!.id).toMatch(/^col_/);
  });
});

describe('real-world dump shapes', () => {
  it('mysqldump', () => {
    const { model, warnings } = parseDdl(`
-- MySQL dump 10.13
/*!40101 SET @OLD_CHARACTER_SET_CLIENT=@@CHARACTER_SET_CLIENT */;
DROP TABLE IF EXISTS \`customers\`;
/*!40101 SET @saved_cs_client     = @@character_set_client */;
CREATE TABLE \`customers\` (
  \`id\` int(11) NOT NULL AUTO_INCREMENT,
  \`name\` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  \`created_at\` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  \`note\` text COMMENT 'free text',
  PRIMARY KEY (\`id\`),
  UNIQUE KEY \`name\` (\`name\`)
) ENGINE=InnoDB AUTO_INCREMENT=12 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
LOCK TABLES \`customers\` WRITE;
INSERT INTO \`customers\` VALUES (1,'it\\'s; tricky',NOW(),NULL);
UNLOCK TABLES;
CREATE TABLE \`orders\` (
  \`id\` bigint unsigned NOT NULL AUTO_INCREMENT,
  \`customer_id\` int(11) NOT NULL,
  PRIMARY KEY (\`id\`),
  KEY \`customer_id\` (\`customer_id\`),
  CONSTRAINT \`orders_ibfk_1\` FOREIGN KEY (\`customer_id\`) REFERENCES \`customers\` (\`id\`) ON DELETE CASCADE
) ENGINE=InnoDB;
`);
    expect(model.dialect).toBe('mysql');
    expect(shapeOf(model).fks).toEqual(['orders(customer_id->id)>customers|orders_ibfk_1|CASCADE|']);
    const customers = Object.values(model.relations).find((r) => r.name === 'customers')!;
    expect(customers.columns[1]!.defaultValue).toBe('NULL');
    expect(customers.columns[3]!.description).toBe('free text');
    const orders = Object.values(model.relations).find((r) => r.name === 'orders')!;
    expect(orders.columns[0]).toMatchObject({ dataType: 'BIGINT UNSIGNED', autoIncrement: true });
    expect(orders.indexes).toMatchObject([{ name: 'customer_id' }]);
    const kinds = warnings.map((w) => w.params!.construct);
    expect(kinds).toContain('/*! */');
    expect(kinds).toContain('DROP statement');
    expect(kinds).toContain('LOCK statement');
    expect(kinds).toContain('INSERT statement'); // the tricky string with an escaped quote and ; did not split the statement
    expect(kinds).toContain('table options');
    expect(kinds).toContain('ON UPDATE');
    expect(kinds).toContain('COLLATE');
    expect(kinds).toContain('CHARACTER SET');
  });

  it('SQLite schema with [bracket] names, AUTOINCREMENT, WITHOUT ROWID', () => {
    const { model, warnings } = parseDdl(`
      CREATE TABLE [Order Details] ([Id] INTEGER PRIMARY KEY AUTOINCREMENT, [Qty] INTEGER NOT NULL CHECK ([Qty] > 0)) WITHOUT ROWID;
    `);
    expect(model.dialect).toBe('sqlite');
    const r = Object.values(model.relations)[0]!;
    expect(r.name).toBe('Order Details');
    expect(r.checks![0]!.columnIds).toEqual([r.columns[1]!.id]);
    expect(warnings.map((w) => w.params!.construct)).toEqual(['table options']);
  });
});
