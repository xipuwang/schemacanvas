import { describe, expect, it } from 'vitest';
import { relationalBuilder } from '@/model/builders';
import type { RelationalModel } from '@/model/types';
import { deepFreeze } from '@/test/deepFreeze';
import { ddlIssues, generateDdl } from './ddl';
import { cycle, kitchenSink, pharmacy, selfRef } from './fixtures';

type D = 'postgresql' | 'sqlite' | 'mysql' | 'generic';
const dialects: D[] = ['postgresql', 'sqlite', 'mysql', 'generic'];
const codes = (m: RelationalModel, d: D): string[] => ddlIssues(m, d).map((i) => i.code);

describe('generateDdl goldens', () => {
  for (const d of ['postgresql', 'mysql', 'sqlite'] as const) {
    it(`pharmacy ${d}`, async () => {
      const r = generateDdl(deepFreeze(pharmacy(d)), d);
      expect(r.issues.filter((i) => i.severity !== 'info')).toEqual([]);
      await expect(r.sql).toMatchFileSnapshot(`__golden__/pharmacy.${d}.sql`);
    });
  }

  it('self reference is inline; FK cycle is broken with ALTER TABLE (postgresql)', () => {
    expect(generateDdl(selfRef('postgresql'), 'postgresql', { header: false }).sql).toBe(`CREATE TABLE "Employee" (
  "Eid" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  "Name" VARCHAR(50) NOT NULL,
  "ManagerEid" INTEGER,
  PRIMARY KEY ("Eid"),
  FOREIGN KEY ("ManagerEid") REFERENCES "Employee" ("Eid") ON DELETE SET NULL
);
`);
    const sql = generateDdl(cycle('postgresql'), 'postgresql', { header: false }).sql;
    expect(sql.indexOf('CREATE TABLE "B"')).toBeGreaterThan(sql.indexOf('CREATE TABLE "A"'));
    expect(sql).toContain('ALTER TABLE "A" ADD CONSTRAINT fk_a_b FOREIGN KEY (b_id) REFERENCES "B" (id);');
    expect(sql.lastIndexOf('ALTER TABLE')).toBeGreaterThan(sql.lastIndexOf('CREATE TABLE'));
    expect(sql).not.toContain('ALTER TABLE "B"');
  });

  it('SQLite never uses ALTER ... ADD CONSTRAINT: cycle FKs stay inline (forward references are legal)', () => {
    const sql = generateDdl(cycle('sqlite'), 'sqlite').sql;
    expect(sql).not.toContain('ALTER TABLE');
    expect(sql).toContain('CONSTRAINT fk_a_b FOREIGN KEY (b_id) REFERENCES "B" (id)');
  });

  it('kitchen sink: mysql golden', () => {
    expect(generateDdl(kitchenSink('mysql'), 'mysql', { header: false }).sql).toBe(`CREATE TABLE users (
  id BIGINT NOT NULL AUTO_INCREMENT,
  email VARCHAR(255) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  score NUMERIC(8, 2) DEFAULT 0,
  created TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE (email),
  CONSTRAINT ck_score CHECK (score >= 0)
);

CREATE TABLE \`order\` (
  \`user id\` BIGINT NOT NULL,
  \`No\` INTEGER NOT NULL,
  note TEXT,
  PRIMARY KEY (\`user id\`, \`No\`),
  FOREIGN KEY (\`user id\`) REFERENCES users (id) ON DELETE CASCADE ON UPDATE NO ACTION
);

CREATE INDEX idx_users_status ON users (status);
CREATE INDEX idx_users_created ON users (created DESC);
`);
  });

  it('kitchen sink: sqlite uses INTEGER PRIMARY KEY AUTOINCREMENT inline and says so for BIGINT', () => {
    const r = generateDdl(kitchenSink('sqlite'), 'sqlite', { header: false });
    expect(r.sql).toContain('id INTEGER PRIMARY KEY AUTOINCREMENT,');
    expect(r.sql).not.toMatch(/PRIMARY KEY \(id\)/);
    expect(r.issues.map((i) => i.code)).toContain('ddl.sqlite.autoincrement-type');
  });

  it('is deterministic regardless of Record key order', () => {
    const m = pharmacy('postgresql');
    const reversed: RelationalModel = {
      ...m,
      relations: Object.fromEntries(Object.entries(m.relations).reverse()),
      foreignKeys: Object.fromEntries(Object.entries(m.foreignKeys).reverse()),
    };
    expect(generateDdl(reversed, 'postgresql').sql).toBe(generateDdl(m, 'postgresql').sql);
  });

  it('does not mutate a frozen model', () => {
    for (const d of dialects) expect(() => generateDdl(deepFreeze(kitchenSink(d)), d)).not.toThrow();
  });
});

describe('identifier quoting', () => {
  const model = (d: D, relName: string, colName: string): RelationalModel => {
    const b = relationalBuilder('q', d);
    b.relation(relName, [{ name: colName, type: 'INTEGER' }], { pk: [colName] });
    return b.build();
  };
  it('quotes only when needed and escapes embedded quotes', () => {
    expect(generateDdl(model('postgresql', 'plain', 'id'), 'postgresql', { header: false }).sql).toContain('CREATE TABLE plain (\n  id INTEGER NOT NULL');
    expect(generateDdl(model('postgresql', 'Mixed', 'a"b'), 'postgresql', { header: false }).sql).toContain('CREATE TABLE "Mixed" (\n  "a""b" INTEGER');
    expect(generateDdl(model('mysql', 'select', 'a`b'), 'mysql', { header: false }).sql).toContain('CREATE TABLE `select` (\n  `a``b` INTEGER');
  });
  it('quoteAll quotes everything', () => {
    expect(generateDdl(model('sqlite', 't', 'id'), 'sqlite', { header: false, quoteAll: true }).sql).toContain('CREATE TABLE "t" (\n  "id" INTEGER');
  });
  it('reserved words are quoted and reported as info', () => {
    const r = generateDdl(model('postgresql', 'user', 'order'), 'postgresql', { header: false });
    expect(r.sql).toContain('CREATE TABLE "user" (\n  "order" INTEGER');
    expect(r.issues.filter((i) => i.code === 'ddl.postgresql.reserved-word').map((i) => i.severity)).toEqual(['info', 'info']);
  });
});

describe('types and defaults', () => {
  const one = (d: D, type: string | undefined, extra: Partial<{ nullable: boolean; default: string; autoIncrement: boolean }> = {}) => {
    const b = relationalBuilder('t', d);
    b.relation('T', [{ name: 'id', type: 'INTEGER' }, { name: 'c', ...(type ? { type } : {}), ...extra }], { pk: ['id'] });
    return generateDdl(b.build(), d, { header: false });
  };
  it('maps across dialects but keeps natively valid spellings', () => {
    expect(one('postgresql', 'BLOB').sql).toContain('c BYTEA');
    expect(one('postgresql', 'JSONB').sql).toContain('c JSONB');
    expect(one('postgresql', 'DOUBLE').sql).toContain('c DOUBLE PRECISION');
    expect(one('mysql', 'BYTEA').sql).toContain('c BLOB');
    expect(one('mysql', 'UUID').sql).toContain('c CHAR(36)');
    expect(one('mysql', 'INT4').sql).toContain('c INT');
    expect(one('sqlite', 'UUID').sql).toContain('c TEXT');
    expect(one('generic', 'DOUBLE').sql).toContain('c DOUBLE PRECISION');
  });
  it('passes unknown and modified types through verbatim with an info issue', () => {
    const r = one('postgresql', 'GEOMETRY(Point)');
    expect(r.sql).toContain('c GEOMETRY(Point)');
    expect(r.issues.find((i) => i.code === 'ddl.postgresql.type-passthrough')?.severity).toBe('info');
    expect(one('mysql', 'INT UNSIGNED').sql).toContain('c INT UNSIGNED');
  });
  it('missing type: warning + dialect fallback; SQLite emits none', () => {
    expect(one('postgresql', undefined).sql).toContain('c TEXT');
    expect(one('mysql', undefined).sql).toContain('c VARCHAR(255)');
    expect(one('sqlite', undefined).sql).toContain('  c,');
    expect(one('postgresql', undefined).issues.map((i) => i.code)).toContain('ddl.postgresql.missing-type');
  });
  it('FK columns without a type inherit the referenced column type', () => {
    const b = relationalBuilder('inh', 'postgresql');
    const p = b.relation('P', [{ name: 'id', type: 'BIGINT' }], { pk: ['id'] });
    const c = b.relation('C', [{ name: 'id', type: 'INTEGER' }, { name: 'pid' }], { pk: ['id'] });
    b.fk(c, ['pid'], p, ['id']);
    const r = generateDdl(b.build(), 'postgresql', { header: false });
    expect(r.sql).toContain('pid BIGINT');
    expect(r.issues.map((i) => i.code)).toContain('ddl.postgresql.type-inherited');
    expect(r.issues.map((i) => i.code)).not.toContain('ddl.postgresql.missing-type');
  });
  it('DEFAULT is verbatim; MySQL VARCHAR gets a length with a warning', () => {
    expect(one('postgresql', 'TEXT', { default: "'it''s'" }).sql).toContain("c TEXT DEFAULT 'it''s'");
    const r = one('mysql', 'VARCHAR');
    expect(r.sql).toContain('c VARCHAR(255)');
    expect(r.issues.map((i) => i.code)).toContain('ddl.mysql.varchar-length');
  });
  it('autoincrement + default drops the default with a warning', () => {
    const r = one('postgresql', 'INTEGER', { autoIncrement: true, default: '5' });
    expect(r.sql).not.toContain('DEFAULT 5');
    expect(r.issues.map((i) => i.code)).toContain('ddl.postgresql.autoincrement-default');
  });
});

describe('autoincrement per dialect', () => {
  const ai = (d: D, pk: string[], type = 'INTEGER') => {
    const b = relationalBuilder('a', d);
    b.relation('T', [{ name: 'a', type, autoIncrement: true }, { name: 'b', type: 'INTEGER' }], { pk });
    return generateDdl(b.build(), d, { header: false });
  };
  it('postgresql/generic use identity columns', () => {
    expect(ai('postgresql', ['a']).sql).toContain('a INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY');
    expect(ai('generic', ['a']).sql).toContain('GENERATED BY DEFAULT AS IDENTITY');
    expect(ai('postgresql', ['a'], 'TEXT').issues.map((i) => i.code)).toContain('ddl.postgresql.autoincrement-type');
    expect(ai('postgresql', ['a'], 'TEXT').sql).toBe('');
  });
  it('mysql: AUTO_INCREMENT must lead a key', () => {
    expect(ai('mysql', ['a']).sql).toContain('a INTEGER NOT NULL AUTO_INCREMENT');
    expect(ai('mysql', ['b', 'a']).sql).toBe('');
    expect(ai('mysql', ['b', 'a']).issues.map((i) => i.code)).toContain('ddl.mysql.autoincrement-key');
    expect(ai('mysql', ['a', 'b']).sql).not.toBe('');
  });
  it('sqlite: only a single-column INTEGER PRIMARY KEY', () => {
    expect(ai('sqlite', ['a']).sql).toContain('a INTEGER PRIMARY KEY AUTOINCREMENT');
    const composite = ai('sqlite', ['a', 'b']);
    expect(composite.sql).toBe('');
    expect(composite.issues.map((i) => i.code)).toContain('ddl.sqlite.autoincrement-pk');
    expect(ai('sqlite', ['b']).issues.map((i) => i.code)).toContain('ddl.sqlite.autoincrement-pk');
    expect(ai('sqlite', ['a'], 'VARCHAR(5)').issues.map((i) => i.code)).toContain('ddl.sqlite.autoincrement-type');
  });
});

describe('refusal and dialect issues', () => {
  it('FK to a non-key refuses to emit DDL in every dialect', () => {
    const b = relationalBuilder('bad');
    const p = b.relation('P', [{ name: 'id', type: 'INTEGER' }, { name: 'x', type: 'INTEGER' }], { pk: ['id'] });
    const c = b.relation('C', [{ name: 'id', type: 'INTEGER' }, { name: 'px', type: 'INTEGER' }], { pk: ['id'] });
    b.fk(c, ['px'], p, ['x']);
    for (const d of dialects) {
      const r = generateDdl(b.build(), d);
      expect(r.sql).toBe('');
      expect(r.issues.map((i) => i.code)).toContain(`ddl.${d}.fk-target-not-key`);
      expect(r.issues.find((i) => i.code.endsWith('fk-target-not-key'))!.severity).toBe('error');
    }
  });
  it('incomplete composite key reference is refused', () => {
    const b = relationalBuilder('bad');
    const p = b.relation('P', [{ name: 'a', type: 'INTEGER' }, { name: 'b', type: 'INTEGER' }], { pk: ['a', 'b'] });
    const c = b.relation('C', [{ name: 'a', type: 'INTEGER' }], { pk: ['a'] });
    b.fk(c, ['a'], p, ['a']);
    expect(generateDdl(b.build(), 'postgresql').sql).toBe('');
  });
  it('a UNIQUE target is a valid key; a unique INDEX target defers the FK until after the index (postgresql)', () => {
    const b = relationalBuilder('u', 'postgresql');
    const p = b.relation('P', [{ name: 'id', type: 'INTEGER' }, { name: 'code', type: 'TEXT' }], { pk: ['id'] });
    p.index('uq_p_code', ['code'], true);
    const c = b.relation('C', [{ name: 'id', type: 'INTEGER' }, { name: 'code', type: 'TEXT' }], { pk: ['id'] });
    b.fk(c, ['code'], p, ['code']);
    const sql = generateDdl(b.build(), 'postgresql', { header: false }).sql;
    expect(sql.indexOf('CREATE UNIQUE INDEX')).toBeLessThan(sql.indexOf('ALTER TABLE'));
  });
  it('dangling ids, duplicates and empty tables are errors', () => {
    const m = pharmacy('postgresql');
    const doc = Object.values(m.relations).find((r) => r.name === 'Doctor')!;
    doc.primaryKey = ['col_gone'];
    expect(codes(m, 'postgresql')).toContain('ddl.postgresql.missing-column');
    const dup = relationalBuilder('d');
    dup.relation('T', [{ name: 'a', type: 'INTEGER' }, { name: 'A', type: 'INTEGER' }]);
    dup.relation('t', [{ name: 'a', type: 'INTEGER' }]);
    dup.relation('Empty', []);
    const c = codes(dup.build(), 'sqlite');
    expect(c).toContain('ddl.sqlite.duplicate-name');
    expect(c).toContain('ddl.sqlite.no-columns');
  });
  it('postgres warns about identifiers over 63 bytes, mysql errors over 64 characters', () => {
    const long = 'x'.repeat(70);
    const b = relationalBuilder('long');
    b.relation(long, [{ name: 'id', type: 'INTEGER' }], { pk: ['id'] });
    expect(ddlIssues(b.build(), 'postgresql').find((i) => i.code === 'ddl.postgresql.identifier-too-long')?.severity).toBe('warning');
    const my = generateDdl(b.build(), 'mysql');
    expect(my.issues.find((i) => i.code === 'ddl.mysql.identifier-too-long')?.severity).toBe('error');
    expect(my.sql).toBe('');
    expect(codes(b.build(), 'sqlite')).not.toContain('ddl.sqlite.identifier-too-long');
  });
  it('type mismatch: error in postgresql/mysql, warning in sqlite/generic', () => {
    const b = relationalBuilder('mm');
    const p = b.relation('P', [{ name: 'id', type: 'INTEGER' }], { pk: ['id'] });
    const c = b.relation('C', [{ name: 'id', type: 'INTEGER' }, { name: 'pid', type: 'TEXT' }], { pk: ['id'] });
    b.fk(c, ['pid'], p, ['id']);
    const sev = (d: D) => ddlIssues(b.build(), d).find((i) => i.code.endsWith('fk-type-mismatch'))?.severity;
    expect(sev('postgresql')).toBe('error');
    expect(sev('mysql')).toBe('error');
    expect(sev('sqlite')).toBe('warning');
    expect(sev('generic')).toBe('warning');
    expect(generateDdl(b.build(), 'sqlite').sql).not.toBe('');
  });
  it('mysql: INT vs BIGINT FK columns, TEXT keys, SET DEFAULT, SET NULL on NOT NULL', () => {
    const b = relationalBuilder('my');
    const p = b.relation('P', [{ name: 'id', type: 'BIGINT' }, { name: 't', type: 'TEXT' }], { pk: ['id'] });
    p.unique('t');
    const c = b.relation('C', [{ name: 'id', type: 'INTEGER' }, { name: 'pid', type: 'INTEGER', nullable: false }], { pk: ['id'] });
    b.fk(c, ['pid'], p, ['id'], { onDelete: 'SET NULL', onUpdate: 'SET DEFAULT' });
    const c2 = codes(b.build(), 'mysql');
    expect(c2).toContain('ddl.mysql.fk-type-mismatch');
    expect(c2).toContain('ddl.mysql.key-lob-column');
    expect(c2).toContain('ddl.mysql.fk-set-default');
    expect(c2).toContain('ddl.mysql.fk-set-null-not-null');
    expect(codes(b.build(), 'postgresql')).not.toContain('ddl.postgresql.key-lob-column');
    expect(ddlIssues(b.build(), 'postgresql').find((i) => i.code.endsWith('fk-set-null-not-null'))?.severity).toBe('warning');
  });
  it('partial index: kept in postgresql/sqlite, omitted with a warning in mysql', () => {
    const b = relationalBuilder('pi');
    const t = b.relation('T', [{ name: 'id', type: 'INTEGER' }, { name: 'a', type: 'INTEGER' }], { pk: ['id'] });
    t.index('ix', ['a'], true);
    t.relation.indexes[0]!.where = 'a > 0';
    t.relation.indexes[0]!.method = 'btree';
    expect(generateDdl(b.build(), 'postgresql', { header: false }).sql).toContain('CREATE UNIQUE INDEX ix ON T USING btree (a) WHERE a > 0;'.replace(' T ', ' "T" '));
    expect(generateDdl(b.build(), 'sqlite', { header: false }).sql).toContain('CREATE UNIQUE INDEX ix ON "T" (a) WHERE a > 0;');
    const my = generateDdl(b.build(), 'mysql', { header: false });
    expect(my.sql).not.toContain('CREATE UNIQUE INDEX');
    expect(my.issues.map((i) => i.code)).toContain('ddl.mysql.partial-index');
  });
  it('every issue carries the model id, an affected ref and a deterministic id', () => {
    for (const i of ddlIssues(kitchenSink('mysql'), 'mysql')) {
      expect(i.affected.length).toBeGreaterThan(0);
      expect(i.id.startsWith(i.code)).toBe(true);
      expect(i.code.startsWith('ddl.mysql.')).toBe(true);
    }
  });
});

describe('schemas', () => {
  const schemaModel = (d: D) => {
    const b = relationalBuilder('s', d);
    const a = b.relation('a', [{ name: 'id', type: 'INTEGER' }], { pk: ['id'], schemaName: 'app' });
    const c = b.relation('c', [{ name: 'id', type: 'INTEGER' }, { name: 'aid', type: 'INTEGER' }], { pk: ['id'], schemaName: 'app' });
    b.fk(c, ['aid'], a, ['id']);
    return b.build();
  };
  it('postgresql qualifies tables and creates the schema', () => {
    const sql = generateDdl(schemaModel('postgresql'), 'postgresql', { header: false }).sql;
    expect(sql).toContain('CREATE SCHEMA IF NOT EXISTS app;');
    expect(sql).toContain('CREATE TABLE app.c (');
    expect(sql).toContain('REFERENCES app.a (id)');
  });
  it('mysql uses CREATE DATABASE; sqlite ignores schemas with an info issue', () => {
    expect(generateDdl(schemaModel('mysql'), 'mysql', { header: false }).sql).toContain('CREATE DATABASE IF NOT EXISTS app;');
    const r = generateDdl(schemaModel('sqlite'), 'sqlite', { header: false });
    expect(r.sql).not.toContain('app');
    expect(r.issues.map((i) => i.code)).toContain('ddl.sqlite.schema-ignored');
  });
});

