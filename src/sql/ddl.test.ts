describe('mysql untyped key columns', () => {
  const wide = (): ReturnType<ReturnType<typeof relationalBuilder>['build']> => {
    const b = relationalBuilder('W', 'mysql');
    const names = ['a', 'b', 'c', 'd', 'e'];
    const p = b.relation('W', names.map((n) => ({ name: n })), { pk: names });
    const c = b.relation('X', [{ name: 'id', type: 'INTEGER' }, ...names.map((n) => ({ name: `w_${n}` }))], { pk: ['id'] });
    b.fk(c, names.map((n) => `w_${n}`), p, names);
    return b.build();
  };
  it('lowers the VARCHAR fallback so a key stays within InnoDB 3072 bytes (utf8mb4), for key and referencing columns alike', () => {
    const sql = generateDdl(wide(), 'mysql').sql;
    expect(sql).toContain('a VARCHAR(153) NOT NULL');
    expect(sql).toContain('w_a VARCHAR(153)');
    expect(sql).not.toContain('VARCHAR(255)');
  });
  const keyed = (pkType: string) => {
    const b = relationalBuilder('K', 'mysql');
    b.relation('T', [{ name: 'a', type: pkType }, { name: 'b' }], { pk: ['a', 'b'] });
    b.relation('Other', [{ name: 'id', type: 'INTEGER' }, { name: 'free' }], { pk: ['id'] });
    return b.build();
  };
  it('lowers only the untyped columns of the over-long key; unrelated untyped columns stay VARCHAR(255)', () => {
    const r = generateDdl(keyed('VARCHAR(700)'), 'mysql');
    expect(r.sql).toContain('b VARCHAR(68) NOT NULL'); // (3072 - 4*700) / 4
    expect(r.sql).toContain('free VARCHAR(255)');
    expect(r.issues.map((i) => i.code)).not.toContain('ddl.mysql.key-too-long');
  });
  it('lowers FK-linked untyped columns in both directions and transitively, nothing else', () => {
    const b = relationalBuilder('L', 'mysql');
    const p = b.relation('P', [{ name: 'a', type: 'VARCHAR(700)' }, { name: 'b' }], { pk: ['a', 'b'] });
    const c = b.relation('C', [{ name: 'pa', type: 'VARCHAR(700)' }, { name: 'pb' }], { pk: ['pa', 'pb'] });
    b.fk(c, ['pa', 'pb'], p, ['a', 'b']);
    const g = b.relation('G', [{ name: 'id', type: 'INTEGER' }, { name: 'ga', type: 'VARCHAR(700)' }, { name: 'gb' }, { name: 'loose' }], { pk: ['id'] });
    b.fk(g, ['ga', 'gb'], c, ['pa', 'pb']);
    const sql = generateDdl(b.build(), 'mysql').sql;
    expect(sql).toContain('b VARCHAR(68) NOT NULL');
    expect(sql).toContain('pb VARCHAR(68)');
    expect(sql).toContain('gb VARCHAR(68)');
    expect(sql).toContain('loose VARCHAR(255)');
  });
  it('sizes TIMESTAMP as the DATETIME MySQL emits, with fractional-second bytes', () => {
    const b = relationalBuilder('T', 'mysql');
    b.relation('T', [{ name: 'a', type: 'VARCHAR(700)' }, { name: 't', type: 'TIMESTAMP' }, { name: 'b' }], { pk: ['a', 't', 'b'] });
    expect(generateDdl(b.build(), 'mysql').sql).toContain('b VARCHAR(66) NOT NULL'); // (3072 - 2800 - 5) / 4
    const b6 = relationalBuilder('T6', 'mysql');
    b6.relation('T', [{ name: 'a', type: 'VARCHAR(700)' }, { name: 't', type: 'TIMESTAMP(6)' }, { name: 'b' }], { pk: ['a', 't', 'b'] });
    expect(generateDdl(b6.build(), 'mysql').sql).toContain('b VARCHAR(66) NOT NULL'); // (3072 - 2800 - 8) / 4
  });
  it('the missing-type warning names the type each untyped column actually got', () => {
    const b = relationalBuilder('W', 'mysql');
    b.relation('T', [{ name: 'a', type: 'VARCHAR(700)' }, { name: 'b' }, { name: 'free' }], { pk: ['a', 'b'] });
    const msgs = generateDdl(b.build(), 'mysql').issues.filter((i) => i.code.endsWith('missing-type')).map((i) => i.explanation);
    expect(msgs).toHaveLength(2);
    expect(msgs.find((m) => m.includes('VARCHAR(68)'))).toMatch(/^b has no type/);
    expect(msgs.find((m) => m.includes('VARCHAR(255)'))).toMatch(/^free has no type/);
  });
  it('typed columns filling the limit: no lowering, key-too-long warning instead', () => {
    const r = generateDdl(keyed('VARCHAR(768)'), 'mysql');
    expect(r.sql).toContain('b VARCHAR(255) NOT NULL');
    expect(r.sql).toContain('free VARCHAR(255)');
    const w = r.issues.find((i) => i.code === 'ddl.mysql.key-too-long');
    expect(w?.severity).toBe('warning');
    expect(w?.affected).toEqual([{ kind: 'column', relationId: expect.any(String), id: expect.any(String) }]);
  });
  it('a lowered length below 32 is not applied either (floor), and warns', () => {
    const r = generateDdl(keyed('VARCHAR(740)'), 'mysql'); // would be 28
    expect(r.sql).toContain('b VARCHAR(255) NOT NULL');
    expect(r.issues.map((i) => i.code)).toContain('ddl.mysql.key-too-long');
    expect(generateDdl(keyed('VARCHAR(736)'), 'mysql').sql).toContain('b VARCHAR(32) NOT NULL'); // exactly the floor
  });
  it('key byte sizes: VARBINARY(n) is n bytes, DECIMAL is packed, PostgreSQL/SQLite are untouched', () => {
    expect(generateDdl(keyed('VARBINARY(2900)'), 'mysql').sql).toContain('b VARCHAR(43) NOT NULL'); // (3072 - 2900) / 4
    expect(generateDdl(keyed('BINARY(2900)'), 'mysql').sql).toContain('b VARCHAR(43) NOT NULL');
    // VARCHAR(700) = 2800 + DECIMAL(65,30) = 30 packed bytes -> (3072 - 2830) / 4
    const d = relationalBuilder('D', 'mysql');
    d.relation('T', [{ name: 'a', type: 'VARCHAR(700)' }, { name: 'd', type: 'DECIMAL(65,30)' }, { name: 'b' }], { pk: ['a', 'd', 'b'] });
    expect(generateDdl(d.build(), 'mysql').sql).toContain('b VARCHAR(60) NOT NULL');
    expect(generateDdl(keyed('VARBINARY(2900)'), 'postgresql').sql).not.toContain('VARCHAR(43)');
    expect(generateDdl(keyed('VARBINARY(2900)'), 'sqlite').sql).not.toContain('VARCHAR(43)');
  });
  it('keeps 255 when no key is at risk, and never changes PostgreSQL output', () => {
    const b = relationalBuilder('N', 'mysql');
    b.relation('T', [{ name: 'id', type: 'INTEGER' }, { name: 'free' }], { pk: ['id'] });
    expect(generateDdl(b.build(), 'mysql').sql).toContain('free VARCHAR(255)');
    expect(generateDdl(wide(), 'postgresql').sql).toContain('TEXT');
  });
});
